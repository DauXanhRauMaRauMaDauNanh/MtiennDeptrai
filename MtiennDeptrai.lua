			local unitUuid = nil
			pcall(function()
				local sel = LocalPlayer:FindFirstChild("selected_trait_unit")
				if sel then unitUuid = sel.Value end
			end)
			if unitUuid and unitUuid ~= "" then
				-- current traits may change through the S2C event; we simply reroll and check via event listener
				if Config.TraitUseToken then
					GameAPI.invoke("request_token_trait_reroll", unitUuid)
				else
					GameAPI.invoke("request_buy_trait_reroll", unitUuid)
				end
			end
		end

		if Config.AutoStatReroll and tick() - lastReroll > 2 then
			local unitUuid = nil
			pcall(function()
				local sel = LocalPlayer:FindFirstChild("selected_trait_unit")
				if sel then unitUuid = sel.Value end
			end)
			if unitUuid and unitUuid ~= "" then
				GameAPI.invoke("reroll_base_stats_all", unitUuid)
			end
		end

		-- Auto sell hatched
		if Config.AutoSellHatched then
			GameAPI.invoke("autosell_hatched_units", Config.SellHatchedRarities)
		end
	end

	-- Stop rerolling when a target trait lands
	GameAPI.onServerEvent("unit_traits_changed", function(unitUuid, traits)
		if not Config.AutoTraitReroll then return end
		local targets = Config.TraitTargets or {}
		if #targets == 0 then return end
		local traitList = traits
		if type(traits) == "table" then
			for _, tname in ipairs(targets) do
				for _, have in pairs(traits) do
					if string.find(string.lower(tostring(have)), string.lower(tname), 1, true) then
						Config.AutoTraitReroll = false
						safe(function() UIRefs.autoTrait:Set(false) end)
						Hub.Notify("Trait Reroll", "🎉 Đã trúng trait '" .. tostring(tname) .. "' — tự dừng reroll!", "success")
						return
					end
				end
			end
		end
	end)

