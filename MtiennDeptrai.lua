local InMatch = {}
Hub.Engines.InMatch = InMatch
do
	local lastAbilityTick = 0
	local lastUpgradeTick = 0
	local myUnitsCache = {}

	local function resetMatchState()
		Flags._votedStart = false
		Flags._setDifficulty = false
		Flags._leftThisMatch = false
		Flags._prioritized = {}
	end

	local function findNearestUnit(pos, maxDist)
		maxDist = maxDist or 3
		local best, bestD = nil, maxDist
		for _, u in ipairs(myUnitsCache) do
			local cf = GameAPI.getUnitPosition(u.model)
			if cf then
				local d = (cf.Position - pos).Magnitude
				if d < bestD then best, bestD = u, d end
			end
		end
		return best
	end
	InMatch.findNearestUnit = findNearestUnit

	local function sortForUpgrade(units)
		local mode = Config.UpgradeStrategy
		if mode == "Cheapest First" then
			table.sort(units, function(a, b) return GameAPI.getUnitCost(a.model) < GameAPI.getUnitCost(b.model) end)
		elseif mode == "Highest Cost" then
			table.sort(units, function(a, b) return GameAPI.getUnitCost(a.model) > GameAPI.getUnitCost(b.model) end)
		elseif mode == "Farm First" then
			table.sort(units, function(a, b)
				local an = string.find(string.lower(a.name), "farm") and 0 or 1
				local bn = string.find(string.lower(b.name), "farm") and 0 or 1
				if an == bn then return GameAPI.getUnitCost(a.model) < GameAPI.getUnitCost(b.model) end
				return an < bn
			end)
		end
		return units
	end

	local function tickMatch()
		local lobby = GameAPI.isInLobby()
		if lobby then
			resetMatchState()
			return
		end

		local wave = GameAPI.getWave()

		-- Auto vote start (match loaded, before first wave)
		if Config.AutoVoteStart and not Flags._votedStart and wave <= 1 then
			local okRes = GameAPI.invoke("vote_start", "Yes")
			Flags._votedStart = true -- avoid spamming even on failure; retried next match
			if okRes ~= nil then Hub.Log("vote_start sent") end
		end

		-- Auto difficulty
		if Config.AutoDifficulty and not Flags._setDifficulty then
			GameAPI.invoke("select_difficulty", Config.Difficulty)
			Flags._setDifficulty = true
		end

		-- Unit cache refresh (2 Hz cadence is enough, loop runs ~4 Hz)
		myUnitsCache = GameAPI.getMyUnits()

		-- Auto priority (once per unit)
		if Config.AutoPriority then
			for _, u in ipairs(myUnitsCache) do
				if not Flags._prioritized[u.uuid] then
					GameAPI.invoke("change_priority", u.model, Config.PriorityMode)
					Flags._prioritized[u.uuid] = true
				end
			end
		end

		-- Auto upgrade (rate-limited, one upgrade per tick)
		if Config.AutoUpgrade and tick() - lastUpgradeTick > 0.8 then
			lastUpgradeTick = tick()
			local units = sortForUpgrade(myUnitsCache)
			local money = GameAPI.getStat("resource")
			for _, u in ipairs(units) do
				local cost = GameAPI.getUnitCost(u.model)
				if cost == math.huge or cost <= money or Config.UpgradeStrategy == "All" then
					GameAPI.invoke("upgrade_unit_ingame", u.model)
					break
				end
			end
		end

		-- Auto ability buff chain
		if Config.AutoAbility and tick() - lastAbilityTick >= (Config.AbilityDelay or 15.5) then
			lastAbilityTick = tick()
			local targets = Config.AbilityUnits or {}
			for _, u in ipairs(myUnitsCache) do
				local wanted = (#targets == 0)
				if not wanted then
					local lname = string.lower(u.name)
					for _, tname in ipairs(targets) do
						if string.find(lname, string.lower(tname), 1, true) then wanted = true break end
					end
				end
				if wanted then
					GameAPI.invoke("use_active_attack", u.model)
				end
			end
		end

		-- Auto leave / sell at wave X
		if Config.AutoLeaveAtWave and not Flags._leftThisMatch and wave >= (Config.LeaveWave or 10) then
			Flags._leftThisMatch = true
			if Config.LeaveAction == "Vote Lose" then
				GameAPI.invoke("vote_lose_game")
			elseif Config.LeaveAction == "Teleport Lobby" then
				GameAPI.invoke("teleport_back_to_lobby")
			elseif Config.LeaveAction == "Sell All Units" then
				for _, u in ipairs(myUnitsCache) do
					GameAPI.invoke("sell_unit_ingame", u.model)
				end
			end
			Hub.Notify("Auto Leave", "Đã tới wave " .. wave .. " → " .. Config.LeaveAction, "warn")
		end
	end

	-- Engine loop: heartbeat-driven, 4 Hz
	local acc = 0
	Hub.trackConnection(RunService.Heartbeat:Connect(function(dt)
		if not Flags.Running then return end
		acc = acc + dt
		if acc < 0.25 then return end
		acc = 0
		safe(tickMatch)
	end))
	Flags.InMatchRunning = true

	-- ---- S2C listeners ----
	-- Auto Skip Wave
	GameAPI.onServerEvent("start_vote_wave_skip", function()
		if Config.AutoSkipWave then
			task.wait(0.5)
			GameAPI.invoke("vote_wave_skip")
		end
	end)

	-- Auto Roguelike card
	GameAPI.onServerEvent("show_roguelike_options", function(options)
		if not Config.AutoRoguelike then return end
		local picks = Config.RoguelikePicks or {}
		local chosen = nil
		if type(options) == "table" then
			for _, pick in ipairs(picks) do
				for id, opt in pairs(options) do
					local name = string.lower(tostring(type(opt) == "table" and (opt.name or opt.id) or opt))
					if string.find(name, pick, 1, true) then
						chosen = id
						break
					end
				end
				if chosen then break end
			end
			if not chosen then
				for id, _ in pairs(options) do chosen = id break end
			end
		end
		if chosen then
			GameAPI.invoke("select_roguelike_option", chosen)
			Hub.Notify("Roguelike", "Đã chọn thẻ: " .. tostring(chosen), "success")
		end
	end)

	-- Auto loot
	GameAPI.onServerEvent("loot_spawned", function(loot)
		if not Config.AutoLoot then return end
		local lootId = loot
		if type(loot) == "table" then lootId = loot.id or loot.uuid or loot[1] end
		if lootId then
			GameAPI.invoke("redeem_loot", lootId)
		end
	end)

	-- End-game vote
	GameAPI.onServerEvent("game_finished", function()
		local action = Config.EndGameAction
		if action == "Off" then return end
		task.wait(1.5)
		local arg = string.lower(action)
		if arg == "replay" or arg == "next" or arg == "lobby" then
			GameAPI.invoke("set_game_finished_vote", arg)
			Hub.Notify("Match Finished", "Auto vote: " .. action, "success")
		end
	end)
end

