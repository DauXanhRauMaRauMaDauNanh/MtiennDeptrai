		return Config.StoryWorld .. "_act" .. tostring(Config.StoryAct)
	end

	local function joinStandard(entry)
		local lobbyName = GameAPI.findOpenLobby(entry.path, entry.pattern)
		if not lobbyName then
			Hub.Notify("Auto Join", "Không tìm thấy phòng trống — thử lại sau " .. Config.JoinRetryDelay .. "s", "warn")
			return false
		end
		GameAPI.invoke("request_join_lobby", lobbyName)
		task.wait(0.8)
		GameAPI.invoke("request_lock_level", lobbyName, buildLevelId(), Config.FriendsOnly, Config.JoinDifficulty)
		task.wait(0.8)
		GameAPI.invoke("request_start_game", lobbyName)
		Hub.Notify("Auto Join", "Đã vào " .. tostring(lobbyName) .. " (" .. buildLevelId() .. ")", "success")
		return true
	end

	function LobbyJoin.tick()
		if not GameAPI.isInLobby() then return end
		local mode = Config.AutoJoinMode
		if mode == "Off" then return end

		if mode == "Story" or mode == "Infinite" then
			if mode == "Infinite" then Config.StoryInfinite = true end
			joinStandard(LOBBY_PATHS.Story)
		elseif mode == "Challenge" then
			joinStandard(LOBBY_PATHS.Challenge)
		elseif mode == "Daily Challenge" then
			joinStandard(LOBBY_PATHS["Daily Challenge"])
		elseif mode == "Raid" then
			joinStandard(LOBBY_PATHS.Raid)
		elseif mode == "Portal" then
			GameAPI.invoke("use_portal")
			task.wait(1)
			GameAPI.invoke("open_portal_level_new")
		elseif mode == "Infinity Castle" then
			GameAPI.invoke("request_start_infinite_tower", Config.InfiniteRoom)
		elseif mode == "Tournament" then
			GameAPI.invoke("request_start_tournament")
		elseif mode == "Dungeon" then
			GameAPI.invoke("dungeon_start")
			task.wait(1.5)
			Hub.Notify("Auto Join", "Dungeon đã bắt đầu — auto runner đang hoạt động", "success")
		end
	end

	function LobbyJoin.dungeonTick()
		if Config.AutoJoinMode ~= "Dungeon" or GameAPI.isInLobby() then return end
		if Config.DungeonAutoChest then
			GameAPI.invoke("dungeon_open_chest")
		end
		if Config.DungeonAutoShrine then
			GameAPI.invoke("dungeon_shrine_accept")
			GameAPI.invoke("dungeon_continue_shop")
		end
		GameAPI.invoke("dungeon_enter_room")
	end

	-- Lobby loop
	task.spawn(function()
		while Flags.Running do
			safe(function()
				if Config.AutoJoinMode ~= "Off" then
					if GameAPI.isInLobby() then
						LobbyJoin.tick()
					else
						LobbyJoin.dungeonTick()
					end
				end
			end)
			task.wait(math.max(2, Config.JoinRetryDelay or 5))
		end
	end)
	Flags.JoinRunning = true
end

