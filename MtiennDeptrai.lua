			lastSummon = tick()
			GameAPI.invoke("buy_from_banner", Config.SummonBanner, Config.SummonCurrency, Config.SummonCount)
		end

		-- Auto trait reroll — acts on the unit selected in game UI
		if Config.AutoTraitReroll and tick() - lastReroll > 1.2 then
