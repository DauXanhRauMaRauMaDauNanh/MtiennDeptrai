do
	local antiAfkConn = nil
	local savedQuality = nil

	function Optimization.setAntiAFK(on)
		if on then
			if antiAfkConn then return end
			antiAfkConn = LocalPlayer.Idled:Connect(function()
				safe(function()
					VirtualUser:CaptureController()
					VirtualUser:ClickButton2(Vector2.new(0, 0))
				end)
			end)
			Hub.trackConnection(antiAfkConn)
		else
			if antiAfkConn then
				pcall(function() antiAfkConn:Disconnect() end)
				antiAfkConn = nil
			end
		end
	end

	function Optimization.setFpsBoost(on)
		if on then
			pcall(function()
				savedQuality = settings().Rendering.QualityLevel
				settings().Rendering.QualityLevel = Enum.QualityLevel.Level01
			end)
			pcall(function() Workspace.GlobalShadows = false end)
			pcall(function() setfpscap(60) end)
			-- hide heavy effects (chunked so a big map cannot freeze the client)
			task.spawn(function()
				local count = 0
				for _, d in ipairs(Workspace:GetDescendants()) do
					if d:IsA("ParticleEmitter") or d:IsA("Trail") or d:IsA("Beam") or d:IsA("Fire") or d:IsA("Smoke") then
						pcall(function() d.Enabled = false end)
					elseif d:IsA("BasePart") and d.Material ~= Enum.Material.SmoothPlastic then
						pcall(function() d.Material = Enum.Material.SmoothPlastic end)
					end
					count = count + 1
					if count % 500 == 0 then task.wait() end
				end
			end)
			Hub.Notify("FPS Boost", "Đã bật Low GFX (tắt bóng + hiệu ứng hạt)", "success")
		else
			pcall(function() Workspace.GlobalShadows = true end)
			pcall(function()
				if savedQuality then settings().Rendering.QualityLevel = savedQuality end
			end)
			Hub.Notify("FPS Boost", "Đã tắt Low GFX", "info")
		end
	end

	function Optimization.set3D(on)
		safe(function()
			if on then
				pcall(function() RunService:Set3dRenderingEnabled(false) end)
				pcall(function() setfpscap(10) end)
				Hub.Notify("AFK Mode", "Đã tắt render 3D (màn hình đen, tiết kiệm tài nguyên)", "warn")
			else
				pcall(function() RunService:Set3dRenderingEnabled(true) end)
				pcall(function() setfpscap(60) end)
			end
		end)
	end
