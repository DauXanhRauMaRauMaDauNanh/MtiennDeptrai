-- ============================================================ MACRO ENGINE
local MacroEngine = {}
Hub.MacroEngine = MacroEngine
do
	local steps = {}
	local recordStart = 0
	MacroEngine.steps = steps

	local MACRO_DIR = "MtiennDeptrai/macros"
	local function macroPath(name)
		return MACRO_DIR .. "/" .. name .. ".json"
	end

	function MacroEngine.clear()
		for i = #steps, 1, -1 do steps[i] = nil end
		recCount:Set("0")
	end

	function MacroEngine.addStep(step)
		step.time = math.floor((tick() - recordStart) * 100) / 100
		step.wave = GameAPI.getWave()
		step.money_req = GameAPI.getStat("resource")
		table.insert(steps, step)
		recCount:Set(tostring(#steps))
	end

	local ensureMacroCapture
	function MacroEngine.startRecording()
		if Flags.MacroRecording then return end
		if ensureMacroCapture then ensureMacroCapture() end
		Flags.MacroRecording = true
		recordStart = tick()
		MacroEngine.clear()
		recStatus:Set("● Recording...")
		Hub.Notify("Macro", "Bắt đầu GHI macro — thao tác đặt/nâng cấp unit sẽ được lưu", "warn")
	end

	function MacroEngine.stopRecording()
		Flags.MacroRecording = false
		recStatus:Set("Idle (saved " .. #steps .. " steps)")
		Hub.Notify("Macro", "Dừng ghi — " .. #steps .. " bước đã ghi", "info")
	end

	function MacroEngine.save(name)
		name = name or Config.MacroName
		safe(Env.mkdir, "MtiennDeptrai")
		safe(Env.mkdir, MACRO_DIR)
		local payload = { name = name, steps = steps }
		local ok, json = pcall(function() return HttpService:JSONEncode(payload) end)
		if ok then
			Env.write(macroPath(name), json)
			Hub.Notify("Macro", "Đã lưu '" .. name .. "' (" .. #steps .. " steps)", "success")
		else
			Hub.Notify("Macro", "Lưu macro thất bại", "error")
		end
	end

	function MacroEngine.load(name)
		name = name or Config.MacroName
		local raw = Env.read(macroPath(name))
		if not raw or #raw < 2 then
			Hub.Notify("Macro", "Không tìm thấy file '" .. name .. "'", "error")
			return
		end
		local ok, data = pcall(function() return HttpService:JSONDecode(raw) end)
		if ok and type(data) == "table" and type(data.steps) == "table" then
			MacroEngine.clear()
			for _, s in ipairs(data.steps) do table.insert(steps, s) end
			recCount:Set(tostring(#steps))
			Hub.Notify("Macro", "Đã tải '" .. name .. "' (" .. #steps .. " steps)", "success")
		end
	end

	function MacroEngine.delete(name)
		Env.write(macroPath(name or Config.MacroName), "")
		Hub.Notify("Macro", "Đã xóa file macro (nếu có)", "info")
	end

	function MacroEngine.startPlayback()
		if Flags.MacroPlaying then return end
		if #steps == 0 then
			Hub.Notify("Macro", "Chưa có bước nào để phát — hãy ghi hoặc load macro", "error")
			Config.MacroPlayback = false
			return
		end
		Flags.MacroPlaying = true
		playStatus:Set("▶ Playing 0/" .. #steps)
		task.spawn(function()
			for i, step in ipairs(steps) do
				if not Flags.MacroPlaying or not Flags.Running then break end
				-- wait conditions
				if Config.MacroWaitMode == "Wave" or Config.MacroWaitMode == "Wave + Money" then
					while Flags.MacroPlaying and GameAPI.getWave() < (step.wave or 0) do task.wait(0.5) end
				end
				if Config.MacroWaitMode == "Money" or Config.MacroWaitMode == "Wave + Money" then
					while Flags.MacroPlaying and GameAPI.getStat("resource") < (step.money_req or 0) do task.wait(0.5) end
				end
				if Config.MacroWaitMode == "Time" and step.time then
					task.wait(math.max(0.2, (step.time - (steps[i - 1] and steps[i - 1].time or 0))))
				end
				if not Flags.MacroPlaying then break end

				safe(function()
					if step.type == "spawn" and step.unit_id and step.pos then
						GameAPI.placeUnit(step.unit_id, CFrame.new(step.pos.x, step.pos.y, step.pos.z))
					elseif step.type == "upgrade" and step.pos then
						local u = InMatch.findNearestUnit(Vector3.new(step.pos.x, step.pos.y, step.pos.z))
						if u then GameAPI.invoke("upgrade_unit_ingame", u.model) end
					elseif step.type == "sell" and step.pos then
						local u = InMatch.findNearestUnit(Vector3.new(step.pos.x, step.pos.y, step.pos.z))
						if u then GameAPI.invoke("sell_unit_ingame", u.model) end
					elseif step.type == "priority" and step.pos then
						local u = InMatch.findNearestUnit(Vector3.new(step.pos.x, step.pos.y, step.pos.z))
						if u then GameAPI.invoke("change_priority", u.model, step.priority or "First") end
					elseif step.type == "ability" and step.pos then
						local u = InMatch.findNearestUnit(Vector3.new(step.pos.x, step.pos.y, step.pos.z))
						if u then GameAPI.invoke("use_active_attack", u.model) end
					end
				end)
				playStatus:Set("▶ Playing " .. i .. "/" .. #steps)
				task.wait(0.35)
			end
			Flags.MacroPlaying = false
			playStatus:Set("Idle")
			Hub.Notify("Macro", "Phát macro hoàn tất", "success")
		end)
	end

	function MacroEngine.stopPlayback()
		Flags.MacroPlaying = false
		playStatus:Set("Stopped")
	end

	-- ---- Recording capture (lazy-installed on startRecording to avoid startup lag) ----
	do
		local tracked = {
			spawn_unit = "spawn",
			upgrade_unit_ingame = "upgrade",
			sell_unit_ingame = "sell",
			change_priority = "priority",
			use_active_attack = "ability",
		}
		local function recordCall(remoteName, args)
			if not Flags.MacroRecording then return end
			local step = { type = tracked[remoteName] }
			for _, a in ipairs(args) do
				if typeof(a) == "CFrame" then
					step.pos = { x = a.Position.X, y = a.Position.Y, z = a.Position.Z }
				elseif typeof(a) == "Instance" then
					step.target_name = a.Name
					if not step.pos then
						local cf = GameAPI.getUnitPosition(a)
						if cf then step.pos = { x = cf.Position.X, y = cf.Position.Y, z = cf.Position.Z } end
					end
				elseif typeof(a) == "Vector3" then
					step.pos = { x = a.X, y = a.Y, z = a.Z }
				elseif type(a) == "string" then
					if tracked[remoteName] == "spawn" and not step.unit_id then step.unit_id = a
					elseif tracked[remoteName] == "priority" then step.priority = a end
				elseif type(a) == "number" and tracked[remoteName] == "spawn" and not step.unit_id then
					step.unit_id = tostring(a)
				end
			end
			MacroEngine.addStep(step)
		end

		local captureInitialized = false
		ensureMacroCapture = function()
			if captureInitialized then return end
			captureInitialized = true

			local hooked = false
			safe(function()
				if Env.hasHookMeta and Env.hasNamecall and type(getnamecallmethod) == "function" then
					local oldNamecall
					oldNamecall = hookmetamethod(game, "__namecall", function(self, ...)
						if not Flags.MacroRecording then
							return oldNamecall(self, ...)
						end
						local method = getnamecallmethod()
						if (method == "InvokeServer" or method == "FireServer") and typeof(self) == "Instance" then
							local rname = self.Name
							if tracked[rname] then
								recordCall(rname, { ... })
							end
						elseif method and tracked[method] then
							recordCall(method, { ... })
						end
						return oldNamecall(self, ...)
					end)
					hooked = (oldNamecall ~= nil)
				end
			end)

			if not hooked then
				local recAcc = 0
				Hub.trackConnection(RunService.Heartbeat:Connect(function(dt)
					if not Flags.MacroRecording then return end
					recAcc = recAcc + dt
					if recAcc < 0.25 then return end
					recAcc = 0
					local unitsFolder = Workspace:FindFirstChild("_UNITS")
					if not unitsFolder then return end
					if not Flags._macroSeen then Flags._macroSeen = {} end
					for _, model in ipairs(unitsFolder:GetChildren()) do
						if not Flags._macroSeen[model] then
							Flags._macroSeen[model] = true
							local stats = model:FindFirstChild("_stats")
							if stats then
								local cf = GameAPI.getUnitPosition(model)
								MacroEngine.addStep({
									type = "spawn",
									unit_id = (stats:FindFirstChild("id") and tostring(stats.id.Value)) or model.Name,
									pos = cf and { x = cf.Position.X, y = cf.Position.Y, z = cf.Position.Z } or nil,
								})
							end
						end
					end
				end))
				Hub.Log("Macro recorder: namecall hook unavailable, using spawn detection fallback")
			end
		end
	end
end

