	-- Endpoint folders (lazy + resilient: game may still be loading)
	local function getC2S()
		local ok, endpoints = pcall(function() return ReplicatedStorage:WaitForChild("endpoints", 20) end)
		if not ok or not endpoints then return nil end
		local c2s = endpoints:FindFirstChild("client_to_server")
		return c2s
	end
	local function getS2C()
		local ok, endpoints = pcall(function() return ReplicatedStorage:WaitForChild("endpoints", 20) end)
		if not ok or not endpoints then return nil end
		return endpoints:FindFirstChild("server_to_client")
	end

	GameAPI.C2S = nil
	GameAPI.S2C = nil
	task.spawn(function()
		GameAPI.C2S = getC2S()
		GameAPI.S2C = getS2C()
	end)

	function GameAPI.refresh()
		GameAPI.C2S = getC2S()
		GameAPI.S2C = getS2C()
		return GameAPI.C2S ~= nil
	end

	function GameAPI.getRemote(name, folder)
		local base = (folder == "s2c") and GameAPI.S2C or GameAPI.C2S
		if not base then
			GameAPI.refresh()
			base = (folder == "s2c") and GameAPI.S2C or GameAPI.C2S
		end
		if not base then return nil end
		return base:FindFirstChild(name)
	end

	function GameAPI.has(name, folder)
		return GameAPI.getRemote(name, folder) ~= nil
	end

	-- Invoke a client_to_server RemoteFunction safely
	function GameAPI.invoke(name, ...)
		local remote = GameAPI.getRemote(name, "c2s")
		if not remote then
			warn("[MtiennDeptrai] Remote not found: " .. tostring(name))
			return nil
		end
		local args = { ... }
		local ok, res = pcall(function()
			return remote:InvokeServer(unpack(args))
		end)
		if not ok then
			warn("[MtiennDeptrai] invoke " .. name .. " failed: " .. tostring(res))
			return nil
		end
		return res
	end

	function GameAPI.fire(name, ...)
		local remote = GameAPI.getRemote(name, "c2s")
		if not remote or not remote.FireServer then return false end
		local args = { ... }
		local ok = pcall(function() remote:FireServer(unpack(args)) end)
		return ok
	end

	function GameAPI.onServerEvent(name, fn)
		local remote = GameAPI.getRemote(name, "s2c")
		if not remote then
			-- retry shortly in case endpoints still loading
			task.spawn(function()
				for i = 1, 20 do
					task.wait(1)
					remote = GameAPI.getRemote(name, "s2c")
					if remote then break end
				end
				if remote then
					Hub.trackConnection(remote.OnClientEvent:Connect(fn))
				end
			end)
			return
		end
		Hub.trackConnection(remote.OnClientEvent:Connect(fn))
	end

