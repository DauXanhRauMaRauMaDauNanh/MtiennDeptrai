	-- Units placed by the local player in the current match
	function GameAPI.getMyUnits()
		local out = {}
		pcall(function()
			local unitsFolder = Workspace:FindFirstChild("_UNITS")
			if not unitsFolder then return end
			local anyOwnerInfo = false
			local all = {}
			for _, model in ipairs(unitsFolder:GetChildren()) do
				local stats = model:FindFirstChild("_stats")
				if stats then
					local mine, known = false, false
					-- 1) _stats.player (ObjectValue -> Player | StringValue -> name | IntValue -> UserId)
					local owner = stats:FindFirstChild("player") or stats:FindFirstChild("owner") or stats:FindFirstChild("player_name")
					if owner then
						if owner:IsA("ObjectValue") and owner.Value ~= nil then
							known = true
							mine = (owner.Value == LocalPlayer)
						elseif owner:IsA("StringValue") and owner.Value ~= "" then
							known = true
							mine = (owner.Value == LocalPlayer.Name)
						elseif owner:IsA("IntValue") and owner.Value > 0 then
							known = true
							mine = (owner.Value == LocalPlayer.UserId)
						end
					end
					-- 2) _stats.player_id / user_id
					if not known then
						local pid = stats:FindFirstChild("player_id") or stats:FindFirstChild("user_id")
						if pid and tonumber(pid.Value) and tonumber(pid.Value) > 0 then
							known = true
							mine = (tonumber(pid.Value) == LocalPlayer.UserId)
						end
					end
					-- 3) attributes on the model
					if not known then
						for _, attr in ipairs({ "Owner", "Player", "OwnerId", "PlayerId" }) do
							local okA, av = pcall(function() return model:GetAttribute(attr) end)
							if okA and av ~= nil then
								known = true
								if type(av) == "string" then mine = (av == LocalPlayer.Name)
								elseif type(av) == "number" then mine = (av == LocalPlayer.UserId)
								elseif type(av) == "table" then mine = (av == LocalPlayer) end
								if known then break end
							end
						end
					end
					if known then anyOwnerInfo = true end
					table.insert(all, { model = model, stats = stats, mine = mine, known = known })
				end
			end
			for _, u in ipairs(all) do
				-- If the game exposes no ownership data at all, treat every unit in
				-- _UNITS as ours (solo play); otherwise filter strictly by owner.
				if (not anyOwnerInfo) or u.mine then
					table.insert(out, {
						model = u.model,
						name  = u.model.Name,
						uuid  = (u.stats:FindFirstChild("uuid") and u.stats.uuid.Value) or u.model.Name,
						id    = (u.stats:FindFirstChild("id") and u.stats.id.Value) or u.model.Name,
						upgrade = (u.stats:FindFirstChild("upgrade") and u.stats.upgrade.Value) or 0,
					})
				end
			end
		end)
		return out
	end

	-- Place a unit with a tolerant signature (CFrame preferred, Vector3 fallback)
	function GameAPI.placeUnit(unitId, pos)
		if typeof(pos) == "CFrame" then
			local res = GameAPI.invoke("spawn_unit", unitId, pos)
			if res ~= nil then return true end
			-- some builds expect Vector3
			return GameAPI.invoke("spawn_unit", unitId, pos.Position) ~= nil
		elseif typeof(pos) == "Vector3" then
			local res = GameAPI.invoke("spawn_unit", unitId, pos)
			if res ~= nil then return true end
			return GameAPI.invoke("spawn_unit", unitId, CFrame.new(pos.X, pos.Y, pos.Z)) ~= nil
		end
		return GameAPI.invoke("spawn_unit", unitId, pos) ~= nil
	end

	-- Estimated placement cost for upgrade ordering ("Cheapest First")
	function GameAPI.getUnitCost(model)
		local ok, v = pcall(function()
			local stats = model:FindFirstChild("_stats")
			if not stats then return math.huge end
			for _, key in ipairs({ "upgrade_cost", "cost", "money", "price" }) do
				local f = stats:FindFirstChild(key)
				if f and tonumber(f.Value) then return tonumber(f.Value) end
			end
			return math.huge
		end)
		return (ok and v) or math.huge
	end

	function GameAPI.getUnitPosition(model)
		local ok, cf = pcall(function()
			if model:IsA("Model") then
				return model:GetPivot()
			end
			return nil
		end)
		return (ok and cf) or nil
	end

	-- Find an open lobby template by folder path e.g. "workspace._LOBBIES.Story"
	function GameAPI.findOpenLobby(folderPath, namePattern)
		local node = Workspace
		for seg in string.gmatch(folderPath, "[^%.]+") do
			node = node:FindFirstChild(seg)
			if not node then return nil end
		end
		local function isOpen(child)
			-- AA lobby templates use an `Owner` ObjectValue (nil = free slot)
			local owner = child:FindFirstChild("Owner")
			if owner and owner:IsA("ObjectValue") then
				if owner.Value ~= nil then return false end
			end
			-- generic markers used by some modes
			for _, d in ipairs(child:GetDescendants()) do
				if d:IsA("ObjectValue") and d.Name == "Owner" and d.Value ~= nil then return false end
				if d:IsA("BoolValue") and d.Name:match("[Oo]ccupied") and d.Value == true then return false end
				if d:IsA("StringValue") and d.Name:match("[Pp]layer") and d.Value ~= "" then return false end
			end
			return true
		end
		for _, child in ipairs(node:GetChildren()) do
			if (not namePattern or child.Name:match(namePattern)) and isOpen(child) then
				return child.Name
			end
		end
		-- fallback: first matching template even if flagged occupied
		for _, child in ipairs(node:GetChildren()) do
			if not namePattern or child.Name:match(namePattern) then
				return child.Name
			end
		end
		return nil
	end
end

