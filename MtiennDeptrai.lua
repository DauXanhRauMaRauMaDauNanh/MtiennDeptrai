	local t = TweenService:Create(obj, TweenInfo.new(duration or 0.2, style or Enum.EasingStyle.Quad, dir or Enum.EasingDirection.Out), props)
	t:Play()
	return t
end
UI.tween = tween

local function registerElement(name, row, keywords)
	table.insert(UI._elements, { name = string.lower(name or ""), row = row, keywords = string.lower(keywords or "") })
end

-- UI callbacks run synchronously so state (Config) is always in sync with the
-- widget; errors are contained so one bad callback cannot break the UI.
local function fireCallback(cb, ...)
	if not cb then return end
	local ok, err = pcall(cb, ...)
	if not ok then warn("[MtiennDeptrai] UI callback error: " .. tostring(err)) end
end

